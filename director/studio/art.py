def _waves(ink_dark, ink_mid, ink_light, w=900):
    def wave(y, amp, n, ph):
        pts = [f'M0 {y}']
        for i in range(n + 1):
            x = i * w / n
            pts.append(f'Q {x - w / n / 2:.0f} {y - amp if (i + ph) % 2 else y + amp} {x:.0f} {y}')
        return ' '.join(pts) + f' L{w} 600 L0 600 Z'
    return [(wave(80, 26, 7, 0), ink_light, .55), (wave(150, 30, 6, 1), ink_mid, .85), (wave(230, 34, 5, 0), ink_dark, 1.15)]


