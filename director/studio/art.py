"""Art for studio projects: concepts per scene, revisions, approval, and the scene visuals the storyboard uses.

* The Art Director's selector (director/art/selector.py) ranks techniques for a scene against the project's own
  profile and says why others are excluded (not in the profile, paid, no verified photo, wrong accuracy...).
* Each technique that the studio can draw has a BUILDER here: it turns the scene's art brief into engine elements in
  the brand's palette. A concept is rendered by the free local engine as stills; nothing is generated by a model.
* A technique whose real material is missing (a licensed photograph) is shown as the engine's REAL PHOTO NEEDED
  panel and marked blocked: the system never fabricates a historical photograph or a watch.
* Technical drawings are labelled as simplified principles, never as a manufacturer's engineering drawing, and draw
  only parts the research supports (case, tube, threads, crown, bezel, case back).

Support levels shown to the user (support_matrix):
  rendered                  the studio drew it from the brief (free, local)
  blocked: missing asset    the technique works but the real material is not in the project
  needs implementation      in the registry but the studio has no builder for it yet
  paid tool                 needs a paid generator (gated, never run here)
  prototype                 a sample exists; not yet in the production engine
"""
