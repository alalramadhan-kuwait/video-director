CATALOGUE = ROOT / 'art/catalogue.yaml'


def catalogue() -> list[dict]:
    """The motion catalogue (art/catalogue.yaml): every template, its purpose and status."""
    return yaml.safe_load(CATALOGUE.read_text(encoding='utf-8'))['templates']


def production_ready(tech: str) -> bool:
    """Only an implemented template with a builder may be picked for a film; experimental and unavailable ones never are."""
    return tech in BUILDERS and any(t['id'] == tech and t['status'] == 'implemented' for t in catalogue())


def _sounds(tech, p, sc, dur):
    """The template's own sound effects, on the beats it draws: a stamp lands, a card is placed, a pin drops, a row
    clicks in, a photo is revealed. Quiet, under the voice; the sounds are the engine's local kit."""
    cue = lambda at, name, gain: sc.setdefault('sfx', []).append({'at': round(at, 2), 'name': name, 'gain': gain}) if at < dur else None
    if tech in ('kinetic_type', 'dark_keynote', 'swiss_grid'):
        for i, ln in enumerate(p.get('lines', [])):
            if ln.get('in') == 'slam': cue(ln.get('at', i * .5) + .1, 'paper_place', -12)
        if p.get('stamp'): cue(p['stamp'].get('at', 1.2) + .05, 'stamp', -9)
    elif tech == 'newspaper_card' and p.get('stamp'):
        cue(p.get('stamp_at', 1.4) + .05, 'stamp', -9)
    elif tech == 'animated_timeline':
        for i, e in enumerate(p.get('events', [])): cue(e.get('at', .25 + i * .6) + .15, 'paper_place', -15)
    elif tech == 'map':
        for pin in p.get('pins', []): cue(pin.get('at', 1.0), 'pin', -12)
        if p.get('date'): cue(p.get('date_at', .6), 'paper_place', -15)
    elif tech == 'spec_card':
        for i, _ in enumerate(p.get('rows', [])): cue(p.get('at', .6) + i * p.get('stagger', .35) + .1, 'click', -16)
    elif tech in ('product_reveal', 'product_macro'):
        cue(.1, 'whoosh', -18)
        if tech == 'product_reveal': cue(1.0, 'shutter', -20)
    elif tech == 'quote_card':
        cue(.3, 'paper_place', -16)


def scene_visual(tech, params, theme, dur, banner=None):
    sc = BUILDERS[tech](copy.deepcopy(params), theme, dur)
    _sounds(tech, params, sc, dur)
    sc['banner'] = banner or None          # explicit: the engine keeps the PREVIOUS scene's banner when the key is missing
    return sc


def missing_assets(tech, params, project_assets: Path) -> list[str]:
    need = NEEDS_ASSETS.get(tech, lambda p: [])(params)
    have = {f.stem for f in project_assets.glob('*')} if project_assets.exists() else set()
    return [a for a in need if a not in have]


# ====================================================================== support matrix
def support_matrix(profile: dict) -> list[dict]:
    reg = yaml.safe_load(REGISTRY.read_text(encoding='utf-8'))['techniques']
    allowed = set(profile.get('art', {}).get('allowed', []))
    forbidden = set(profile.get('art', {}).get('forbidden', []))
    out = []
    for t in reg:
        tid = t['id']
        if t['status'] == 'paid' or t['cost'] == 'paid':
            lvl = 'paid tool'
        elif tid in forbidden:
            lvl = 'forbidden by the brand'
        elif t['status'] == 'prototype' or (tid in BUILDERS and not production_ready(tid)):
            lvl = 'prototype'
        elif tid in BUILDERS:
            lvl = 'supported' + (' (needs real material)' if tid in NEEDS_ASSETS else '')
        else:
            lvl = 'needs implementation'
        out.append({'id': tid, 'name': t['name'], 'level': lvl, 'in_profile': tid in allowed, 'cost': t['cost'],
                    'accuracy': t['accuracy'], 'limits': t.get('limits', '')})
    return out


# ====================================================================== concept jobs
def _render_concept(studio, pid, work: Path, sc: dict, dur: float, brand: str):
    sb = {'width': 720, 'height': 1280, 'fps': 30, 'dir': 'rtl', **style(brand), 'scenes': [{**sc, 'dur': dur}]}
    adir = studio.pdir(pid) / 'assets'
    if adir.exists():
        (work / 'assets').mkdir(parents=True, exist_ok=True)
        for f in adir.glob('*'):
            dst = work / 'assets' / f.name
            if not dst.exists(): dst.write_bytes(f.read_bytes())
    files = engine.stills(sb, work, [dur * .45, dur - .15], scale=0.75)
    return [studio.put_file(pid, f, 'png') for f in files], sb


def concepts(studio, pid, task, scene):
    """Job: rank techniques for one scene, then render every option the studio can draw."""
    st = studio.state(pid)
    brief = brief_for(studio, pid, st)
    sb = brief['scenes'][scene]
    prof = studio.profile(st['brand'])
    reg = load_registry(REGISTRY)
    rec = recommend({'id': scene, 'beat': sb['beat'], 'accuracy': sb.get('accuracy', 'high'), 'assets': sb.get('assets', []),
                     'real_person': sb.get('real_person', False), 'max_cost': 0}, prof, reg, n=6)
    out = []
    opts = [o for o in rec['options'] if o['technique'] in sb.get('concepts', {})]
    extra = [t for t in sb.get('concepts', {}) if t not in [o['technique'] for o in opts] and t in BUILDERS]
    for k, o in enumerate(opts + [{'technique': t, 'name': t, 'score': None, 'reasons': ['proposed by the art brief'], 'warnings': []} for t in extra]):
        tid = o['technique']
        params = sb['concepts'][tid]
        cid = f'{scene}-{tid}'
        miss = missing_assets(tid, params, studio.pdir(pid) / 'assets')
        dur = sb.get('dur', 5.0)
        visual = scene_visual(tid, params, params.get('theme', sb.get('theme', 'tk-bone')), dur, sb.get('banner'))
        stills, _ = _render_concept(studio, pid, studio.pdir(pid) / 'work/concepts' / cid, visual, dur, st['brand'])
        support = 'blocked: missing asset' if miss else 'rendered'
        out.append({'id': cid, 'scene': scene, 'technique': tid, 'name': o.get('name', tid), 'rank': k + 1, 'score': o.get('score'),
                    'reasons': o.get('reasons', []), 'warnings': o.get('warnings', []) + ([f'missing: {", ".join(miss)}'] if miss else []),
                    'support': support, 'missing': miss, 'params': params, 'theme': params.get('theme', sb.get('theme', 'tk-bone')),
                    'versions': [{'v': 1, 'stills': stills, 'changes': {}, 'status': None}]})
        task.unit(scene=scene, concept=cid)
    studio.act(pid, 'art_concepts', {'scene': scene, 'concepts': out, 'excluded': rec['excluded'],
                                     'ranked': [o['technique'] for o in rec['options']]}, actor='system')
    return {'scene': scene, 'concepts': [c['id'] for c in out]}


REVISIONS = {'theme': 'Change the paper colour', 'zoom': 'Push in closer', 'text_size': 'Bigger text', 'slower': 'Slower motion'}


def apply_changes(params: dict, theme: str, changes: dict):
    p, th = copy.deepcopy(params), theme
    if changes.get('theme'): th = changes['theme']
    if changes.get('text_size'):
        f = float(changes['text_size'])
        for ln in p.get('lines', []): ln['size'] = round(ln.get('size', 66) * f)
        for t in p.get('tags', []): t['size'] = round(t.get('size', 40) * f)
        for lb in p.get('labels', []): lb['size'] = round(lb.get('size', 40) * f)          # map labels
    if changes.get('zoom'):
        p['zoom'] = p['push'] = float(changes['zoom'])
        if isinstance(p.get('view'), dict) and 'span' in p['view']:                         # a map: show a smaller area
            p['view'] = {**p['view'], 'span': round(p['view']['span'] / float(changes['zoom']), 2)}
    if changes.get('slower'):
        f = float(changes['slower'])
        for k in ('screw_at', 'close_at', 'open_at', 'date_at', 'stamp_at', 'card_at'):
            if k in p: p[k] = round(p[k] * f, 2)
    return p, th


CHANGE_CHIPS = {'theme:tk-ink': 'Darker paper', 'theme:tk-bone': 'Lighter paper', 'text_size:1.2': 'Bigger text',
                'zoom:1.18': 'Push in closer', 'slower:1.4': 'Slower'}


def effective_changes(tech: str, params: dict, theme: str) -> list[str]:
    """The change chips that actually alter this drawing: the engine scene is built before and after the change and
    compared. A change this technique ignores (e.g. 'Bigger text' on a map whose labels have a fixed size) is not offered."""
    if tech not in BUILDERS:
        return []
    try:
        base = json.dumps(scene_visual(tech, params, theme, 5.0), sort_keys=True, default=str)
    except Exception:                                          # incomplete parameters: cannot tell, so do not hide anything
        return list(CHANGE_CHIPS)
    out = []
    for chip in CHANGE_CHIPS:
        k, v = chip.split(':')
        p2, th2 = apply_changes(params, theme, {k: v})
        try:
            if json.dumps(scene_visual(tech, p2, th2, 5.0), sort_keys=True, default=str) != base: out.append(chip)
        except Exception:
            pass
    return out


def revise(studio, pid, task, concept, params=None, theme=None):
    """Job: make the next version of a concept from the open change request (structured changes are applied by the
    system; a free-text note is carried on the version for the art operator)."""
    st = studio.state(pid)
    c = st['art']['concepts'][concept]
    req = next(q for q in st['art']['requests'] if q['concept'] == concept and q['status'] == 'open')
    last = c['versions'][-1]
    if params is None:
        params, theme = apply_changes(last.get('params', c['params']), last.get('theme', c['theme']), req['changes'])
    brief = brief_for(studio, pid, st)['scenes'][c['scene']]
    dur = brief.get('dur', 5.0)
    visual = scene_visual(c['technique'], params, theme, dur, brief.get('banner'))
    v = last['v'] + 1
    stills, _ = _render_concept(studio, pid, studio.pdir(pid) / 'work/concepts' / f'{concept}-v{v}', visual, dur, st['brand'])
    same = next((x['v'] for x in reversed(c['versions']) if x['stills'] == stills), None)   # content-addressed: equal paths = identical images
    task.unit(scene=c['scene'], concept=concept)
    studio.act(pid, 'art_revision', {'concept': concept, 'scene': c['scene'],
                                     'version': {'v': v, 'stills': stills, 'changes': req['changes'], 'note': req['note'],
                                                 'params': params, 'theme': theme, 'status': None, 'from': last['v'],
                                                 **({'no_visible_change': True, 'same_as': same} if same else {})}}, actor='system')
    return {'concept': concept, 'version': v}


