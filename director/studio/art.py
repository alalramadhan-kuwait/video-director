def style(brand):
    """The renderer style: the paper themes, with the brand config's fonts and captions (brand/<id>.json)."""
    from .. import brand as B
    st = json.loads((ROOT / 'director/studio/assets/tk-style.json').read_text(encoding='utf-8'))
