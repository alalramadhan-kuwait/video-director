def backdrop(sc: dict, asset: str, dur: float, credit: str = '', move: str = 'in') -> dict:
    """A related photograph behind a scene of words (a stamp, a number, a card): full frame, a slow drift, darkened so
    the words stay readable, its credit on screen. The scene's world adds only its sound (the photo is the world)."""
    s0, s1 = (1.16, 1.04) if move == 'out' else (1.04, 1.16)
    shade = ('<svg xmlns="http://www.w3.org/2000/svg" width="760" height="1320"><rect width="760" height="1320" fill="#08090B" '
             'fill-opacity=".62"/></svg>')
    sc['elements'] = [{'type': 'image', 'asset': asset, 'desc': asset, 'w': 720, 'h': 1280, 'x': 360, 'y': 640, 'frame': False, 'fit': 'cover',
                       'behind': True, 'noBoil': True, 'scale': [[0, s0], [dur, s1, 'linear']]},
                      {'type': 'svg', 'w': 760, 'h': 1320, 'svg': shade, 'x': 360, 'y': 640, 'behind': True, 'still': True}] + sc['elements']
    if credit:
        sc['elements'].append({'type': 'text', 'text': short_credit(credit), 'font': 'cap', 'size': 18, 'color': PAPER, 'paper': INK, 'x': 360, 'y': CREDIT_Y, 'depth': 0,
                               'w': 600, 'align': 'center', 'z': 40, 'in': {'type': 'fade', 'at': .3}})
    sc['full_frame'] = True
    return sc


def _sounds(tech, p, sc, dur):
    """The template's own sound effects, on the beats it draws: a stamp lands, a card is placed, a pin drops, a row
    clicks in, a photo is revealed. Quiet, under the voice; the sounds are the engine's local kit."""
    cue = lambda at, name, gain: sc.setdefault('sfx', []).append({'at': round(at, 2), 'name': name, 'gain': gain}) if at < dur else None
    if tech in ('kinetic_type', 'dark_keynote', 'swiss_grid'):
        for i, ln in enumerate(p.get('lines', [])):
            if ln.get('in') == 'slam': cue(ln.get('at', i * .5) + .1, 'paper_place', -12)
        if p.get('stamp'): cue(p['stamp'].get('at', 1.2) + .05, 'stamp', -9)
    elif tech == 'newspaper_card' and p.get('stamp'):
        cue(p.get('stamp_at', 1.4) + .05, 'stamp', -9)
    elif tech == 'animated_timeline':
        for i, e in enumerate(p.get('events', [])): cue(e.get('at', .25 + i * .6) + .15, 'paper_place', -15)
    elif tech == 'map':
        for pin in p.get('pins', []): cue(pin.get('at', 1.0), 'pin', -12)
        for r in p.get('routes', []):                # a train on the route is heard passing
            if r.get('marker', p.get('marker')) == 'train': cue(r.get('at', 0), 'train', -10)
        if p.get('date'): cue(p.get('date_at', .6), 'paper_place', -15)
    elif tech == 'spec_card':
        for i, _ in enumerate(p.get('rows', [])): cue(p.get('at', .6) + i * p.get('stagger', .35) + .1, 'click', -16)
    elif tech in ('product_reveal', 'product_macro'):
        cue(.1, 'whoosh', -18)
        if tech == 'product_reveal': cue(1.0, 'shutter', -20)
    elif tech == 'quote_card':
        cue(.3, 'paper_place', -16)
    elif tech == 'paper_cutout':
        cue(.2, 'paper_place', -12)
    elif tech == 'watch_movement':                  # the movement running, then the parts lifting apart
        cue(0, 'watch_run', -20); cue(p.get('explode_at', 2.4), 'whoosh', -18)
    elif tech == 'stat_counter':                     # ticks while the digits roll, one firm click as the number lands
        land, run = p.get('land', 1.8), p.get('dur', 1.5)
        cue(max(.1, land - run), 'tick_pair', -20); cue(land, 'click', -11)
    elif tech == 'part_of_whole':
        cue(p.get('land', 1.9), 'click', -13)
    elif tech == 'trend_chart':
        cue(p.get('at', .5), 'whoosh', -20)
    elif tech == 'compare_bars':                    # the bars are drawn, not paper: one click as they rise
        cue(p.get('at', .5) + .1, 'click', -15)


STEADY = {'image', 'photo', 'cutout', 'igpost', 'reveal'}     # real pictures: never the paper boil (the engine agrees)


def steady(sc: dict) -> dict:
    """Photos and cut-outs of people and watches hold still: no line boil (it read as trembling, Étienne's review)."""
    for e in sc.get('elements', []):
        if e.get('type') in STEADY: e.setdefault('noBoil', True)
    return sc


def scene_visual(tech, params, theme, dur, banner=None, seed=None):
    """The engine scene for a template: its elements, its sounds, no boil on its photos, and a camera that really moves
    (motion.ensure: at least 3 %, seeded by `seed`, else by the template and the scene's length)."""
    sc = BUILDERS[tech](copy.deepcopy(params), theme, dur)
    _sounds(tech, params, sc, dur)
    sc['banner'] = banner or None          # explicit: the engine keeps the PREVIOUS scene's banner when the key is missing
    steady(sc)
    motion.ensure(sc, dur, seed if seed is not None else f'{tech}|{dur}|{banner or ""}')
    return sc


def missing_assets(tech, params, project_assets: Path) -> list[str]:
    need = NEEDS_ASSETS.get(tech, lambda p: [])(params)
    have = {f.stem for f in project_assets.glob('*')} if project_assets.exists() else set()
    return [a for a in need if a not in have]


# ====================================================================== support matrix
def support_matrix(profile: dict) -> list[dict]:
    reg = yaml.safe_load(REGISTRY.read_text(encoding='utf-8'))['techniques']
    allowed = set(profile.get('art', {}).get('allowed', []))
    forbidden = set(profile.get('art', {}).get('forbidden', []))
    out = []
    for t in reg:
        tid = t['id']
        if t['status'] == 'paid' or t['cost'] == 'paid':
            lvl = 'paid tool'
        elif tid in forbidden:
            lvl = 'forbidden by the brand'
        elif t['status'] == 'prototype' or (tid in BUILDERS and not production_ready(tid)):
            lvl = 'prototype'
        elif tid in BUILDERS:
            lvl = 'supported' + (' (needs real material)' if tid in NEEDS_ASSETS else '')
        else:
            lvl = 'needs implementation'
        out.append({'id': tid, 'name': t['name'], 'level': lvl, 'in_profile': tid in allowed, 'cost': t['cost'],
                    'accuracy': t['accuracy'], 'limits': t.get('limits', '')})
    return out


