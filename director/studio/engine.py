"""The free, local renderer: Time Keeper's paper-story engine (vendor/paper-story, copied read-only with hashes).

Headless Chromium draws each frame from a storyboard JSON; ffmpeg encodes. Nothing is generated by a model, so a
render is repeatable. Stills take seconds, a 70-second draft about two minutes at 720x1280 on 4 workers.
"""
from __future__ import annotations
import json, os, subprocess, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ENGINE = ROOT / 'vendor/paper-story'
RENDER = ENGINE / 'scripts/render.mjs'


def _env():
    g = subprocess.run(['npm', 'root', '-g'], capture_output=True, text=True).stdout.strip()
    env = {**os.environ, 'NODE_PATH': os.path.join(g, 'playwright', 'node_modules') + os.pathsep + g,
           'PLAYWRIGHT_BROWSERS_PATH': '/opt/pw-browsers'}
    for k in ('ELEVENLABS_API_KEY', 'FAL_KEY', 'HIGGSFIELD_API_KEY'):
        env.pop(k, None)                       # the renderer never needs a key; make sure it cannot see one
    return env


def run(sb_path: Path, *args, timeout=1800) -> subprocess.CompletedProcess:
    sb_path = Path(sb_path).resolve()
    args = [str(Path(a).resolve()) if isinstance(a, Path) else str(a) for a in args]
    r = subprocess.run(['node', str(RENDER), str(sb_path), *args], capture_output=True, text=True,
                       env=_env(), cwd=str(Path(sb_path).parent), timeout=timeout)
    if r.returncode != 0:
        msg = ((r.stderr or '') + '\n' + (r.stdout or ''))[-1200:]
        raise RuntimeError(f'render failed ({r.returncode}): {msg}')
    return r


def stills(sb: dict, workdir: Path, times: list[float], scale=0.75) -> list[Path]:
    """PNG stills of a storyboard at the given times (seconds from the start)."""
    workdir.mkdir(parents=True, exist_ok=True)
    p = workdir / 'still.json'; p.write_text(json.dumps(sb, ensure_ascii=False), encoding='utf-8')
    out = workdir / 'stills'
    if out.exists():
        for f in out.glob('*.png'): f.unlink()
    run(p, '--still', ','.join(f'{t:.2f}' for t in times), '--scale', scale, '-o', out)
    return sorted(out.glob('*.png'))


def check(sb: dict, workdir: Path) -> list[str]:
    """The engine's own layout check (faces covered, prints over prints, things on the captions, cut by the frame).
    Written next to the storyboard's own files (voice/, assets/, logo), because their paths are relative to it."""
    workdir.mkdir(parents=True, exist_ok=True)
    p = workdir / '_check.json'; p.write_text(json.dumps(sb, ensure_ascii=False), encoding='utf-8')
    r = subprocess.run(['node', str(RENDER), str(p.resolve()), '--check'], capture_output=True, text=True, env=_env(),
                       cwd=str(workdir), timeout=1800)
    lines = [l for l in (r.stdout + r.stderr).splitlines() if l.strip()]
    if r.returncode != 0 and not any(l.startswith('scene ') for l in lines):      # exit 1 also means "faults found"
        raise RuntimeError(f'layout check failed ({r.returncode}): ' + '\n'.join(lines[-8:]))
    return lines


def video(sb_path: Path, out: Path, scale=1.0, workers=4, extra=(), progress=None) -> str:
    """Render the film. `progress(pct)` is called each time the renderer passes another 10 % of the frames."""
    import re as _re
    sb_path = Path(sb_path).resolve()
    p = subprocess.Popen(['node', str(RENDER), str(sb_path), '-o', str(Path(out).resolve()), '--scale', str(scale), '--workers', str(workers),
                          *map(str, extra)], stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, env=_env(), cwd=str(sb_path.parent),
                         start_new_session=True)               # its own process group: the renderer and its browsers stop together
    pidf = sb_path.parent / 'render.pid'; pidf.write_text(str(p.pid))      # a restarted server kills it (see kill_orphans)
    lines, last = [], 0
    for line in p.stdout:
        lines.append(line)
        m = _re.match(r'\s+(\d+)%', line)
        if m and progress:
            pct = int(m.group(1)) // 10 * 10
            while last < pct:
                last += 10; progress(last)
    p.wait(timeout=3600)
    pidf.unlink(missing_ok=True)
    log = ''.join(lines)
    if p.returncode != 0:
        raise RuntimeError(f'render failed ({p.returncode}): {log[-1200:]}')
    while progress and last < 100:
        last += 10; progress(last)
    return log


def kill_orphans(root: Path) -> list[int]:
    """Renderer processes left by a server that stopped mid-render (their render.pid files)."""
    import signal
    killed = []
    for pf in Path(root).glob('*/work/**/render.pid'):           # draft renders and Co-Pilot scene clips
        try:
            pid = int(pf.read_text().strip())
            cmd = Path(f'/proc/{pid}/cmdline').read_bytes().decode(errors='replace') if Path(f'/proc/{pid}').exists() else ''
            if 'render.mjs' in cmd:
                try: os.killpg(pid, signal.SIGTERM)             # the renderer and the browsers it started
                except OSError: os.kill(pid, signal.SIGTERM)
                killed.append(pid)
        except (ValueError, OSError):
            pass
        pf.unlink(missing_ok=True)
    return killed
